#!/usr/bin/env bash
# Builds only on an operator-provided host; does not allocate or launch GPUs.
set -euo pipefail
cd "$(dirname "$0")/.."
: "${RUNTIME_ROOT:?Set an external, fresh runtime directory}"
: "${PYTHON_BIN:?Set a Python 3.10 interpreter}"
export FA3_CUDA_HOME=${FA3_CUDA_HOME:-/usr/local/cuda-12.6}
export DG_CUDA_HOME=${DG_CUDA_HOME:-/usr/local/cuda-13.2}
"$PYTHON_BIN" - "$RUNTIME_ROOT" <<'PY'
import pathlib, platform, sys
assert sys.version_info[:2] == (3, 10), 'use the recorded Python 3.10 series'
assert platform.system() == 'Linux' and platform.machine() == 'x86_64', 'H100 runtime needs Linux x86_64'
root = pathlib.Path(sys.argv[1]).resolve()
repository = pathlib.Path.cwd()
assert root != repository and repository not in root.parents, 'runtime must be outside Git'
assert not root.exists(), 'runtime directory must be fresh'
PY
test -x "$FA3_CUDA_HOME/bin/nvcc"
test -x "$DG_CUDA_HOME/bin/nvcc"
"$PYTHON_BIN" -m venv "$RUNTIME_ROOT/venv"
export PYTHON_BIN="$RUNTIME_ROOT/venv/bin/python"
"$PYTHON_BIN" -m pip install -r production/requirements-h100.txt --extra-index-url https://download.pytorch.org/whl/cu126
"$PYTHON_BIN" -m pip install --no-deps 'muon-optimizer @ git+https://github.com/KellerJordan/Muon.git@f98f1cacc0263b04290753e32be8d498c1efc806'
bash scripts/build_h100_fa3.sh
git clone https://github.com/deepseek-ai/DeepGEMM.git "$RUNTIME_ROOT/DeepGEMM"
git -C "$RUNTIME_ROOT/DeepGEMM" checkout --detach 559d79fb6994a58b8a15b4b93bf13ccc16edf247
git -C "$RUNTIME_ROOT/DeepGEMM" submodule update --init --recursive
env CUDA_HOME="$FA3_CUDA_HOME" DG_FORCE_BUILD=1 \
  "$PYTHON_BIN" -m pip install --no-build-isolation --no-deps "$RUNTIME_ROOT/DeepGEMM"
"$PYTHON_BIN" -m pip install --no-deps --no-build-isolation .
"$PYTHON_BIN" -m pip check
# Use shell quoting generated by Python; paths are not interpolated as code.
"$PYTHON_BIN" - "$RUNTIME_ROOT" "$FA3_CUDA_HOME" "$DG_CUDA_HOME" <<'PY'
from pathlib import Path
import shlex, sys
root, fa, dg = map(Path, sys.argv[1:])
values = {'PYTHON_BIN': root / 'venv/bin/python', 'PYTHONPATH': root / 'fa3-site',
          'FA3_CUDA_HOME': fa, 'CUDA_HOME': dg, 'DG_JIT_NVCC_COMPILER': dg / 'bin/nvcc',
          'DG_JIT_CACHE_DIR': root / 'deepgemm-jit', 'OMP_NUM_THREADS': '4', 'MKL_NUM_THREADS': '4'}
(root / 'activate-runtime.sh').write_text(''.join(f'export {key}={shlex.quote(str(value))}\n' for key, value in values.items())
                                        + f'export PATH={shlex.quote(str(root / "venv/bin"))}:"$PATH"\n')
PY
